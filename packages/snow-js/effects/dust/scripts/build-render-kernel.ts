// Builds src/render-kernel.wat into the base64 module committed at
// src/render-kernel-wasm.ts. Uses the wabt npm package; the generated module
// is committed so normal builds need no wasm toolchain. Run:
// bun scripts/build-render-kernel.ts
// Pass --check to exit 1 when the committed module is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import initWabt from "wabt";

const root = new URL("..", import.meta.url).pathname;
const watPath = join(root, "src", "render-kernel.wat");
const wabt = await initWabt();
const mod = wabt.parseWat(watPath, readFileSync(watPath, "utf8"));
mod.resolveNames();
mod.validate();
const { buffer } = mod.toBinary({ log: false, write_debug_names: false });
const base64 = Buffer.from(buffer).toString("base64");
const generated =
  `// GENERATED by scripts/build-render-kernel.ts from src/render-kernel.wat -\n` +
  `// do not edit; rebuild with \`bun scripts/build-render-kernel.ts\`.\n` +
  `export const RENDER_KERNEL_WASM =\n  "${base64}";\n`;
const outPath = join(root, "src", "render-kernel-wasm.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(outPath, "utf8") !== generated) {
    console.error(
      "src/render-kernel-wasm.ts is out of date with src/render-kernel.wat - run: bun scripts/build-render-kernel.ts",
    );
    process.exit(1);
  }
  console.log("render kernel wasm up to date");
} else {
  writeFileSync(outPath, generated);
  console.log(`render kernel built: ${base64.length} base64 chars`);
}
