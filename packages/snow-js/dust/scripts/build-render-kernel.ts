// Builds src/render-kernel.wat into the base64 module committed at
// src/render-kernel-wasm.ts. Requires wabt's wat2wasm on PATH (one-time
// build; the generated module is committed so normal builds need no wasm
// toolchain). Run: bun scripts/build-render-kernel.ts
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

const root = new URL("..", import.meta.url).pathname;
const watPath = join(root, "src", "render-kernel.wat");
const tmp = mkdtempSync(join(tmpdir(), "render-kernel-"));
const wasmPath = join(tmp, "render-kernel.wasm");
const res = spawnSync("wat2wasm", [watPath, "-o", wasmPath], { stdio: "inherit" });
if (res.status !== 0) {
  rmSync(tmp, { recursive: true, force: true });
  throw new Error(`wat2wasm failed with status ${res.status}`);
}
const base64 = readFileSync(wasmPath).toString("base64");
rmSync(tmp, { recursive: true, force: true });
writeFileSync(
  join(root, "src", "render-kernel-wasm.ts"),
  `// GENERATED by scripts/build-render-kernel.ts from src/render-kernel.wat -\n` +
    `// do not edit; rebuild with \`bun scripts/build-render-kernel.ts\`.\n` +
    `export const RENDER_KERNEL_WASM =\n  "${base64}";\n`,
);
console.log(`render kernel built: ${base64.length} base64 chars`);
